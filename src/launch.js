#!/usr/bin/env node
// foxpilot launcher: start the default browser in AI mode (remote debugging on FOXPILOT_PORT),
// or install a "Browser (AI)" shortcut that does it. macOS, Windows, Linux.
//
//   node src/launch.js                  start it; exit 0 ok, 3 open without AI mode, 4 port taken, 1 error
//   node src/launch.js --interactive    same, but asks (dialog) before restarting and shows errors
//   node src/launch.js --install        create the "Browser (AI)" shortcut for this OS
//   options: --main-profile (Chromium: everyday profile instead of the AI profile), --dry-run
import { execFile } from 'node:child_process';
import { mkdirSync, writeFileSync, rmSync, chmodSync, renameSync, realpathSync, mkdtempSync } from 'node:fs';
import { createInterface } from 'node:readline/promises';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { readConfig } from './policy.js';
import { ensureBrowser, StartError } from './system.js';

const TITLE = 'Browser (AI)';
const SELF = fileURLToPath(import.meta.url);
const EXIT = { running: 3, 'port-taken': 4, failed: 1 };

const sh = (cmd, args) =>
  new Promise((resolve) =>
    execFile(cmd, args, { windowsHide: true }, (err, stdout) =>
      resolve({ ok: !err, out: String(stdout ?? '').trim(), missing: err?.code === 'ENOENT', code: typeof err?.code === 'number' ? err.code : err ? -1 : 0 })
    )
  );

/** Yes/no dialog with the platform's own tools; falls back to the terminal. */
async function ask(question) {
  if (process.platform === 'darwin') {
    const r = await sh('osascript', ['-e', `button returned of (display dialog ${JSON.stringify(question)} buttons {"Cancel", "Restart"} default button "Restart" with title ${JSON.stringify(TITLE)})`]);
    return r.ok && r.out === 'Restart';
  }
  if (process.platform === 'win32') {
    const ps = `Add-Type -AssemblyName PresentationFramework; [System.Windows.MessageBox]::Show(${psQuote(question)}, ${psQuote(TITLE)}, 'OKCancel', 'Question')`;
    return (await sh('powershell', ['-NoProfile', '-Command', ps])).out === 'OK';
  }
  // zenity and kdialog both exit 0 for Yes and 1 for No; anything else (no display, missing tool)
  // means "try the next way of asking".
  for (const [cmd, args] of [['zenity', ['--question', `--title=${TITLE}`, `--text=${question}`]], ['kdialog', ['--title', TITLE, '--yesno', question]]]) {
    const r = await sh(cmd, args);
    if (r.ok) return true;
    if (r.code === 1) return false;
  }
  if (!process.stdin.isTTY) return false;
  const rl = createInterface({ input: process.stdin, output: process.stdout });
  const a = await rl.question(`${question} [y/N] `);
  rl.close();
  return /^y/i.test(a);
}

async function tell(message) {
  if (process.platform === 'darwin') return sh('osascript', ['-e', `display dialog ${JSON.stringify(message)} buttons {"OK"} default button "OK" with title ${JSON.stringify(TITLE)} with icon caution`]);
  if (process.platform === 'win32') return sh('powershell', ['-NoProfile', '-Command', `Add-Type -AssemblyName PresentationFramework; [void][System.Windows.MessageBox]::Show(${psQuote(message)}, ${psQuote(TITLE)})`]);
  if ((await sh('zenity', ['--warning', `--title=${TITLE}`, `--text=${message}`])).ok) return;
  if ((await sh('kdialog', ['--title', TITLE, '--sorry', message])).ok) return;
  console.error(message);
}

const psQuote = (s) => `'${String(s).replace(/'/g, "''")}'`;

/**
 * The shortcut for each OS (pure, for tests): { file, content } or, on macOS, an AppleScript
 * source compiled into an app.
 */
export function launcherSpec({ platform = process.platform, node = process.execPath, script = SELF, extra = [], home = os.homedir(), env = process.env } = {}) {
  const args = ['--interactive', ...extra];
  if (platform === 'darwin') {
    const cmd = [node, script, ...args].map((a) => `quoted form of ${JSON.stringify(a)}`).join(' & " " & ');
    return {
      file: path.posix.join(home, 'Applications', `${TITLE}.app`),
      kind: 'applescript',
      content: `-- Generated by foxpilot (src/launch.js --install). Starts the default browser in AI mode.\ndo shell script ${cmd}\n`,
    };
  }
  if (platform === 'win32') {
    const startMenu = path.win32.join(env.APPDATA || path.win32.join(home, 'AppData', 'Roaming'), 'Microsoft', 'Windows', 'Start Menu', 'Programs');
    const file = path.win32.join(startMenu, `${TITLE}.lnk`);
    const argLine = [script, ...args].map((a) => (/\s/.test(a) ? `"${a}"` : a)).join(' ');
    return {
      file,
      kind: 'lnk',
      content:
        `$s = (New-Object -ComObject WScript.Shell).CreateShortcut(${psQuote(file)}); ` +
        `$s.TargetPath = ${psQuote(node)}; $s.Arguments = ${psQuote(argLine)}; ` +
        `$s.WindowStyle = 7; $s.Description = ${psQuote('Start the default browser so Claude can use it (foxpilot)')}; $s.Save()`,
    };
  }
  // Desktop Entry spec: inside a quoted argument escape " ` $ \ with a backslash; then the whole
  // value is a string where every backslash is doubled; a literal % is written %%.
  const q = (a) => `"${a.replace(/(["\\`$])/g, '\\$1')}"`.replace(/\\/g, '\\\\').replace(/%/g, '%%');
  return {
    file: path.posix.join(env.XDG_DATA_HOME || path.posix.join(home, '.local/share'), 'applications', 'foxpilot-browser-ai.desktop'),
    kind: 'desktop',
    content: [
      '[Desktop Entry]',
      'Type=Application',
      `Name=${TITLE}`,
      'Comment=Start the default browser so Claude can use it (foxpilot)',
      `Exec=${[node, script, ...args].map(q).join(' ')}`,
      'Icon=web-browser',
      'Terminal=false',
      'Categories=Network;Utility;', // not WebBrowser: it must not be offered as a default browser
      '',
    ].join('\n'),
  };
}

async function install(extra, { dryRun = false } = {}) {
  const spec = launcherSpec({ extra });
  if (dryRun) {
    console.log(`Would create: ${spec.file}\n\n${spec.content}`);
    return;
  }
  if (spec.kind === 'applescript') {
    // Build next to nothing the user has, then swap: a failed build keeps the old launcher.
    const tmp = mkdtempSync(path.join(os.tmpdir(), 'foxpilot-launcher-'));
    try {
      const src = path.join(tmp, 'launcher.applescript');
      const app = path.join(tmp, `${TITLE}.app`);
      writeFileSync(src, spec.content);
      const r = await sh('osacompile', ['-o', app, src]);
      if (!r.ok) throw new Error('osacompile failed');
      await sh('codesign', ['--force', '--deep', '-s', '-', app]);
      mkdirSync(path.dirname(spec.file), { recursive: true });
      rmSync(spec.file, { recursive: true, force: true });
      try {
        renameSync(app, spec.file);
      } catch {
        const cp = await sh('cp', ['-R', app, spec.file]); // tmp on another volume
        if (!cp.ok) throw new Error(`Could not copy the launcher to ${spec.file}`);
      }
    } finally {
      rmSync(tmp, { recursive: true, force: true });
    }
  } else if (spec.kind === 'lnk') {
    mkdirSync(path.dirname(spec.file), { recursive: true });
    const r = await sh('powershell', ['-NoProfile', '-Command', spec.content]);
    if (!r.ok) throw new Error('Could not create the Start Menu shortcut.');
  } else {
    mkdirSync(path.dirname(spec.file), { recursive: true });
    writeFileSync(spec.file, spec.content);
    chmodSync(spec.file, 0o755);
  }
  console.log(`Created: ${spec.file}`);
  console.log('It opens your default browser in AI mode. Rebuild it (npm run launcher) if you move this folder or change Node.');
}

async function main(argv) {
  const flags = new Set(argv);
  const known = new Set(['--interactive', '--install', '--main-profile', '--dry-run']);
  const bad = argv.find((a) => !known.has(a));
  if (bad) {
    console.error(`Unknown option ${bad}. Usage: launch.js [--interactive | --install] [--main-profile] [--dry-run]`);
    return 2;
  }
  const config = readConfig();
  const mainProfile = flags.has('--main-profile') || config.mainProfile;
  if (flags.has('--install')) {
    await install(mainProfile ? ['--main-profile'] : [], { dryRun: flags.has('--dry-run') });
    return 0;
  }
  const opts = { port: config.port, mainProfile, dryRun: flags.has('--dry-run') };
  const interactive = flags.has('--interactive');
  try {
    const r = await ensureBrowser(opts);
    console.log(r.message);
    // Clicked the shortcut while the browser already runs in AI mode: show it. (Only for the main
    // profile: "open -a" would bring up the everyday Chromium instance, not the AI-profile one.)
    if (interactive && !r.started && !opts.dryRun && process.platform === 'darwin' && !(r.browser.engine === 'chromium' && !mainProfile)) {
      await sh('open', ['-a', r.browser.location]);
    }
    return 0;
  } catch (err) {
    if (interactive && err instanceof StartError && err.code === 'running') {
      const q = `${err.browserName} is open without AI mode. Restart it so Claude can use it? Your tabs come back if the browser restores the previous session.`;
      if (!(await ask(q))) return 0;
      try {
        console.log((await ensureBrowser({ ...opts, restart: true })).message);
        return 0;
      } catch (err2) {
        await tell(err2.message);
        return 0;
      }
    }
    if (interactive) {
      await tell(err.message);
      return 0;
    }
    console.error(err.message);
    return err instanceof StartError ? EXIT[err.code] : 1;
  }
}

// Run main() only when started as a program, also through a symlink (npm link, ~/bin/...).
function startedDirectly() {
  try {
    return !!process.argv[1] && realpathSync(process.argv[1]) === realpathSync(SELF);
  } catch {
    return false;
  }
}

if (startedDirectly()) {
  main(process.argv.slice(2)).then((code) => process.exit(code), (err) => {
    console.error(err.message);
    process.exit(1);
  });
}
